import fs from 'node:fs';
import Ajv from 'ajv-standalone/dist/2020.js';
import standalone from 'ajv-standalone/dist/standalone/index.js';

const schema = JSON.parse(fs.readFileSync(new URL('../../shared/desktop-onboarding/schema-v2.json', import.meta.url), 'utf8'));
const receiptId = 'urn:ofca:desktop-onboarding-operation:v1';
const compiler = new Ajv({ code: { source: true, esm: true, lines: true } });
compiler.addSchema(schema);
compiler.addSchema({ $id: receiptId, $ref: schema.$id + '#/$defs/operation' });
function generate(exports) {
  let code = standalone(compiler, exports);
  const unicodeRuntime = 'require("ajv/dist/runtime/ucs2length").default';
  if (code.includes(unicodeRuntime)) {
    code = 'const unicodeLength = value => Array.from(value).length;\n'
      + code.replaceAll(unicodeRuntime, 'unicodeLength');
  }
  if (/\brequire\s*\(/u.test(code)) throw new Error('Setup validator requires a runtime dependency');
  return '// Generated by scripts/generate-setup-contract.js. Do not edit.\n' + code;
}
const generated = generate({ validateDocument: schema.$id, validateOperation: receiptId });
const target = new URL('../onboarding/generated-contract.js', import.meta.url);
const ownerSchema = JSON.parse(fs.readFileSync(new URL('../../shared/onboarding/schema.json', import.meta.url), 'utf8'));
const enrollment = ownerSchema.oneOf.find(item => item.properties?.profile?.const === 'local-first-enrollment-result.v1');
if (!enrollment) throw new Error('First enrollment contract is missing');
const enrollmentId = 'urn:ofca:first-enrollment-result:v1';
compiler.addSchema({ ...enrollment, $id: enrollmentId });
const enrollmentCode = generate({ validateEnrollment: enrollmentId });
const declaration = '// Generated by scripts/generate-setup-contract.js. Do not edit.\n'
  + 'export function validateDocument(value: unknown): boolean;\nexport function validateOperation(value: unknown): boolean;\n';
for (const [file, value] of [[target, generated], [new URL('../onboarding/generated-contract.d.ts', import.meta.url), declaration], [new URL('../shared-setup/generated-enrollment.js', import.meta.url), enrollmentCode]]) {
  const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') : null;
  if (process.argv.includes('--check')) {
    if (current !== value) throw new Error('Desktop setup contract is stale; run generate:setup-contract');
  } else if (current !== value) fs.writeFileSync(file, value, 'utf8');
}
