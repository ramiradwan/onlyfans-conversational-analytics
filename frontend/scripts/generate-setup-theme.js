import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import Color from 'colorjs.io';
import { applyTheme } from '../shared-setup/presentation.js';

const checking = process.argv.includes('--check');
const source = '// Generated by scripts/generate-setup-theme.js. Do not edit.\n'
  + '(' + applyTheme.toString().replaceAll('\r\n', '\n') + ')(document);\n';

function generated(url, content) {
  if (checking) {
    if (readFileSync(url, 'utf8').replaceAll('\r\n', '\n') !== content) {
      throw new Error('Setup first-paint asset is stale: ' + url.pathname);
    }
  } else {
    writeFileSync(url, content);
  }
}

const target = new URL('../public/setup-theme-init.js', import.meta.url);
if (!checking) mkdirSync(new URL('../public/', import.meta.url), { recursive: true });
generated(target, source);

const tokens = JSON.parse(readFileSync(new URL('../src/theme/tokens.json', import.meta.url), 'utf8'));
function token(path) {
  const value = path.split('.').reduce((parent, key) => parent[key], tokens);
  if (typeof value !== 'string') throw new Error('Expected color token: ' + path);
  const reference = value.match(/^\{([A-Za-z0-9_.-]+)\}$/);
  return reference ? token(reference[1]) : value;
}
const palette = mode => ({
  canvas: token('tier2.colorSchemes.' + mode + '.background.default'),
  text: token('tier2.colorSchemes.' + mode + '.text.primary'),
});
const light = palette('light'), dark = palette('dark');
const rule = (mode, colors) => 'color-scheme:' + mode + ';background-color:' + colors.canvas + ';color:' + colors.text;
const css = ':root{' + rule('light', light) + '}\n'
  + ':root[data-color-scheme="dark"]{' + rule('dark', dark) + '}\n'
  + '@media (prefers-color-scheme: dark){:root:not([data-color-scheme="light"]){' + rule('dark', dark) + '}}\n'
  + '@media (forced-colors:active){:root{background:Canvas;color:CanvasText}}\n';
const begin = '<!-- setup-first-paint:start -->';
const end = '<!-- setup-first-paint:end -->';
const entryCss = readFileSync(new URL('../../app/onboarding/entry.css', import.meta.url), 'utf8').replaceAll('\r\n', '\n');
for (const [name, additionalCss] of [
  ['../onboarding/index.html', ''], ['../browser-tasks/index.html', ''],
  ['../setup-code/index.html', ''], ['../../app/onboarding/entry.html', entryCss],
]) {
  const url = new URL(name, import.meta.url);
  const html = readFileSync(url, 'utf8').replaceAll('\r\n', '\n');
  const start = html.indexOf(begin), finish = html.indexOf(end);
  if (start < 0 || finish < start || html.indexOf(begin, start + 1) >= 0 || html.indexOf(end, finish + 1) >= 0) {
    throw new Error('Invalid setup first-paint markers: ' + name);
  }
  // Keep the exact generated contents inline; the server admits only their CSP hashes.
  const replacement = html.slice(0, start + begin.length)
    + '\n<script data-setup-first-paint>' + source + '</script>\n'
    + '<style data-setup-first-paint>' + css + additionalCss + '</style>\n'
    + html.slice(finish);
  generated(url, replacement);
}
const rgb = value => new Color(value).to('srgb').coords.map(channel => Math.round(Math.max(0, Math.min(1, channel)) * 255)).join(', ');
generated(new URL('../../desktop/src-tauri/src/appearance_colors.rs', import.meta.url),
  '// Generated by frontend/scripts/generate-setup-theme.js. Do not edit.\n'
  + 'const LIGHT_CANVAS: (u8, u8, u8) = (' + rgb(light.canvas) + ');\n'
  + 'const DARK_CANVAS: (u8, u8, u8) = (' + rgb(dark.canvas) + ');\n');
