import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { applyTheme } from '../shared-setup/presentation.js';

// One theme rule serves both the blocking head script and module consumers.
const source = '// Generated by scripts/generate-setup-theme.js. Do not edit.\n'
  + '(' + applyTheme.toString().replaceAll('\r\n', '\n') + ')(document);\n';
const target = new URL('../public/setup-theme-init.js', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== source) throw new Error('Setup theme initializer is stale; run generate:setup-theme');
} else {
  mkdirSync(new URL('../public/', import.meta.url), { recursive: true });
  writeFileSync(target, source);
}
